import assert from 'node:assert/strict';
globalThis.Deno = { env: { get: key => ({ SUPABASE_URL: 'https://example.com', SUPABASE_ANON_KEY: 'public-test', GEMINI_API_KEY: 'fake-key' })[key] }, serve: () => {} };
const { handler } = await import('../supabase/functions/generate-answer/index.ts');
let calls = []; let mode = 'success';
globalThis.fetch = async (url, options) => {
  calls.push({ url, options });
  if(url.endsWith('/auth/v1/user')) return Response.json({ id: 'test-user' });
  if(mode === 'quota') return Response.json({}, { status: 429 });
  if(mode === 'blocked') return Response.json({ promptFeedback: { blockReason: 'SAFETY' } });
  return Response.json({ candidates: [{ finishReason: 'STOP', content: { parts: [{ thought: true, text: 'internal' }, { text: 'Prayer offers comfort [1]. Sources: [1] Example — Speaker.' }] } }] });
};
const req = (body, signedIn = true) => new Request('https://example.com', { method: 'POST', headers: signedIn ? { Authorization: 'Bearer test-token' } : {}, body: JSON.stringify(body) });
assert.equal((await handler(new Request('https://example.com', { method: 'OPTIONS' }))).status, 204);
assert.equal((await handler(req({}, false))).status, 401);
assert.equal(calls.length, 0);
assert.equal((await handler(req({ question: 'test', context_talks: [] }))).status, 200);
assert.equal(calls.length, 1);
assert.equal((await handler(req({ question: 'test', context_talks: [{}] }))).status, 400);
const body = { question: 'What about prayer?', context_talks: [{ title: 'Example', speaker: 'Speaker', text: 'Prayer offers comfort.' }] };
calls = [];
const response = await handler(req(body));
assert.equal(response.status, 200);
assert.equal(response.headers.get('Access-Control-Allow-Origin'), '*');
assert.equal((await response.json()).answer.includes('internal'), false);
assert.ok(calls[1].url.includes('gemini-3.5-flash-lite:generateContent'));
const payload = JSON.parse(calls[1].options.body);
assert.equal(JSON.parse(payload.contents[0].parts[0].text).context_talks[0].source, 1);
assert.ok(payload.systemInstruction.parts[0].text.includes('Never invent'));
assert.equal((await handler(req({ ...body, context_talks: [{ ...body.context_talks[0], text: 'x'.repeat(200001) }] }))).status, 413);
mode = 'quota'; assert.equal((await handler(req(body))).status, 429);
mode = 'blocked'; assert.equal((await handler(req(body))).status, 502);
console.log('Passed: preflight, authentication, validation, empty context, context limits, model selection, prompt sources, answer extraction and upstream errors. No live calls made.');
